import { Injectable, inject } from '@angular/core';
import { HttpClient, HttpParams } from '@angular/common/http';
import { Observable } from 'rxjs';
import { AdminOrder, AdminOrderDetail, CreateOrderRequest, Order, OrderSummary } from '../models/order';
import { PagedResult } from '../models/paged-result';
import { API_BASE_URL } from './api-config';

@Injectable({ providedIn: 'root' })
export class OrderService {
  private http = inject(HttpClient);
  private baseUrl = `${API_BASE_URL}/Orders`;
  private adminBaseUrl = `${API_BASE_URL}/Admin/Orders`;

  createOrder(request: CreateOrderRequest): Observable<Order> {
    return this.http.post<Order>(this.baseUrl, request);
  }

  getMyOrders(): Observable<OrderSummary[]> {
    return this.http.get<OrderSummary[]>(this.baseUrl);
  }

  getOrder(id: number): Observable<Order> {
    return this.http.get<Order>(`${this.baseUrl}/${id}`);
  }

  getAllOrdersAdmin(): Observable<AdminOrder[]> {
    return this.http.get<AdminOrder[]>(this.adminBaseUrl);
  }

  getAllOrdersAdminPaged(
    pageNumber: number,
    pageSize: number,
    search?: string,
    status?: string,
    payment?: string
  ): Observable<PagedResult<AdminOrder>> {
    let params = new HttpParams()
      .set('pageNumber', pageNumber)
      .set('pageSize', pageSize);

    if (search) {
      params = params.set('search', search);
    }

    if (status) {
      params = params.set('status', status);
    }

    if (payment) {
      params = params.set('payment', payment);
    }

    return this.http.get<PagedResult<AdminOrder>>(`${this.adminBaseUrl}/paged`, { params });
  }

  // courierName/trackingNumber are only sent when marking an order Shipped;
  // a blank tracking number is generated by the server.
  updateOrderStatus(id: number, status: string, shipment?: { courierName: string; trackingNumber?: string }): Observable<void> {
    return this.http.put<void>(`${this.adminBaseUrl}/${id}/status`, { status, ...shipment });
  }

  cancelOrder(id: number, reason?: string): Observable<void> {
    return this.http.put<void>(`${this.baseUrl}/${id}/cancel`, { reason });
  }

  getInvoice(id: number): Observable<Blob> {
    return this.http.get(`${this.baseUrl}/${id}/invoice`, { responseType: 'blob' });
  }

  getOrderAdmin(id: number): Observable<AdminOrderDetail> {
    return this.http.get<AdminOrderDetail>(`${this.adminBaseUrl}/${id}`);
  }

  getInvoiceAdmin(id: number): Observable<Blob> {
    return this.http.get(`${this.adminBaseUrl}/${id}/invoice`, { responseType: 'blob' });
  }

  exportOrdersCsv(search?: string, status?: string, payment?: string): Observable<Blob> {
    let params = new HttpParams();

    if (search) {
      params = params.set('search', search);
    }

    if (status) {
      params = params.set('status', status);
    }

    if (payment) {
      params = params.set('payment', payment);
    }

    return this.http.get(`${this.adminBaseUrl}/export`, { params, responseType: 'blob' });
  }
}
